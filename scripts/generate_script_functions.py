#!/usr/bin/env python3
"""Generate the d: function table on tenant-scripts/functions.mdx from ScriptLibrary.CATALOG.

The catalog in the Darpan component is the one source: the script editor read it at runtime, and this page carries
it for people. Run after the catalog changes; --check exits 1 when the page has drifted (for CI).

    python3 scripts/generate_script_functions.py --component <path to runtime/component/darpan> [--check]
"""
import argparse
import pathlib
import re
import sys

PAGE = pathlib.Path(__file__).resolve().parent.parent / 'tenant-scripts' / 'functions.mdx'
LIBRARY = 'src/main/groovy/darpan/script/ScriptLibrary.groovy'
START = '{/* functions:start (generated by scripts/generate_script_functions.py; do not edit by hand) */}'
END = '{/* functions:end */}'
ENTRY = re.compile(r"""\[name:\s*(?P<q1>['"])(?P<name>.*?)(?P=q1),\s*help:\s*(?P<q2>['"])(?P<help>.*?)(?P=q2)\]""")


def read_catalog(component: pathlib.Path) -> list[tuple[str, str]]:
    source = (component / LIBRARY).read_text(encoding='utf-8')
    block = source.split('CATALOG = [', 1)
    if len(block) != 2:
        sys.exit(f'CATALOG not found in {component / LIBRARY}')
    body = block[1].split('].collect', 1)[0]
    entries = [(m.group('name'), m.group('help')) for m in ENTRY.finditer(body)]
    if not entries:
        sys.exit('CATALOG has no entries; the pattern no longer matches the source')
    return entries


def table(entries: list[tuple[str, str]]) -> str:
    def cell(text: str) -> str:
        return text.replace('|', '\\|')
    # The catalog's words as written: they start with a variable name (x, s, list), which must keep its case.
    rows = [f'| `d:{cell(name)}` | {cell(help_text)} |' for name, help_text in entries]
    return '\n'.join(['| Function | Returns |', '| --- | --- |', *rows])


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--component', required=True, type=pathlib.Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()

    page = PAGE.read_text(encoding='utf-8')
    if START not in page or END not in page:
        sys.exit(f'{PAGE} is missing the generated-table markers')
    head, rest = page.split(START, 1)
    _, tail = rest.split(END, 1)
    updated = f'{head}{START}\n{table(read_catalog(args.component))}\n{END}{tail}'

    if args.check:
        if updated != page:
            sys.exit('tenant-scripts/functions.mdx is out of date with ScriptLibrary.CATALOG; run the generator.')
        print('tenant-scripts/functions.mdx matches ScriptLibrary.CATALOG')
        return
    PAGE.write_text(updated, encoding='utf-8')
    print(f'wrote {PAGE}')


if __name__ == '__main__':
    main()
